"""Render the per-host governing layout from the canonical role definitions.

Every file here is a render target: edit `src/tempo/agents/*.md`, `src/tempo/rules/protocol.md`, or this
module, then run `tempo render`. `tempo render --check` (and the test suite) fail on drift.
"""

from __future__ import annotations

import json
from pathlib import Path

from tempo.roles import TEMPO_TOOLS, Role, protocol, roles

BEGIN = "<!-- tempo:protocol begin (generated by `tempo render`; edit src/tempo/rules/protocol.md) -->"
END = "<!-- tempo:protocol end -->"
NOTE = "<!-- Generated by `tempo render` from src/tempo/agents/{id}.md; edit that file, never this one. -->"

# Files whose only tempo-owned content is the managed protocol block.
BLOCK_FILES = {"CLAUDE.md": "claude", "AGENTS.md": "codex", ".github/copilot-instructions.md": "copilot"}

CLAUDE_TOOLS = {"read": ["Read"], "search": ["Grep", "Glob"], "write": ["Write"]}
COPILOT_TOOLS = {"read": ["read"], "search": ["search"], "write": ["edit"]}


def _json(data: dict) -> str:
    return json.dumps(data, indent=2) + "\n"


def _claude_agent(role: Role) -> str:
    tools = [t for c in role.tools if c in CLAUDE_TOOLS for t in CLAUDE_TOOLS[c]]
    if role.creates or not role.subagent:
        tools.append("Edit")
    if "spawn" in role.tools:
        tools.append("Agent(" + ", ".join(roles()[r].agent_name for r in role.spawns) + ")")
    if "tempo" in role.tools:
        tools += [f"mcp__tempo__{t}" for t in TEMPO_TOOLS]
    return (f"---\nname: {role.agent_name}\ndescription: {json.dumps(role.description)}\ntools: {', '.join(tools)}\n---\n"
            f"{NOTE.format(id=role.id)}\n\n{role.body}")


def _copilot_agent(role: Role) -> str:
    tools = [t for c in role.tools if c in COPILOT_TOOLS for t in COPILOT_TOOLS[c]]
    if "spawn" in role.tools:
        tools.append("agent")
    if "tempo" in role.tools:
        tools += [f"tempo/{t}" for t in TEMPO_TOOLS]
    lines = ["---", f"name: {role.agent_name}", f"description: {json.dumps(role.description)}",
             f"tools: {json.dumps(tools)}"]
    if role.spawns:
        lines.append(f"agents: {json.dumps([roles()[r].agent_name for r in role.spawns])}")
    return "\n".join(lines) + f"\n---\n{NOTE.format(id=role.id)}\n\n{role.body}"


def _codex_agent(role: Role) -> str:
    if "'''" in role.body:
        raise ValueError(f"{role.id} body may not contain ''' (TOML literal string delimiter)")
    return (f"# Generated by `tempo render` from src/tempo/agents/{role.id}.md; edit that file, never this one.\n"
            f"name = {json.dumps(role.agent_name)}\n"
            f"description = {json.dumps(role.description)}\n"
            f"developer_instructions = '''\n{role.body}'''\n")


def _command(host: str, event: str) -> str:
    return f"tempo hook {host} {event}"


def layout() -> dict[str, str]:
    """Every fully generated file, by repo-relative path."""
    files: dict[str, str] = {}
    for role in roles().values():
        files[f".claude/agents/{role.agent_name}.md"] = _claude_agent(role)
        files[f".github/agents/{role.agent_name}.agent.md"] = _copilot_agent(role)
        if role.subagent:
            files[f".codex/agents/{role.agent_name}.toml"] = _codex_agent(role)
        else:
            # Codex has no root custom agent; the supervisor passes this file as the session's instructions.
            files[f".codex/{role.agent_name}.md"] = f"{NOTE.format(id=role.id)}\n\n{role.body}"

    files[".claude/settings.json"] = _json({"hooks": {
        ev: [{"hooks": [{"type": "command", "command": _command("claude", ev), "timeout": 30}]}]
        for ev in ("PreToolUse", "SubagentStop")
    }})
    files[".mcp.json"] = _json({"mcpServers": {"tempo": {"command": "tempo", "args": ["mcp"]}}})

    files[".github/hooks/tempo.json"] = _json({"version": 1, "hooks": {
        ev: [{"type": "command", "bash": _command("copilot", ev), "powershell": _command("copilot", ev),
              "timeoutSec": 30}]
        for ev in ("preToolUse", "subagentStop")
    }})
    files[".vscode/mcp.json"] = _json({"servers": {"tempo": {"type": "stdio", "command": "tempo", "args": ["mcp"]}}})

    files[".codex/hooks.json"] = _json({"hooks": {
        ev: [{"hooks": [{"type": "command", "command": _command("codex", ev), "timeout": 30}]}]
        for ev in ("PreToolUse", "SubagentStart", "SubagentStop")
    }})
    files[".codex/config.toml"] = (
        "# Generated by `tempo render`; edit src/tempo/render.py, never this file.\n"
        "# One open subagent thread: Codex hooks cannot name the calling agent (AGENT_PLAN.md section 8.4).\n"
        "[agents]\nmax_concurrent_threads_per_session = 1\n\n"
        '[mcp_servers.tempo]\ncommand = "tempo"\nargs = ["mcp"]\n'
    )
    return files


def block() -> str:
    return f"{BEGIN}\n{protocol().rstrip()}\n{END}\n"


def merge_block(existing: str | None, new_block: str) -> str:
    if not existing:
        return new_block
    start, end = existing.find(BEGIN.split(" (")[0]), existing.find(END)
    if start != -1 and end != -1:
        return existing[:start] + new_block + "\n" + existing[end + len(END):].lstrip("\n")
    return new_block + "\n" + existing


def expected(root: Path) -> dict[str, str]:
    """The full expected content of every rendered path under `root`."""
    files = layout()
    for path in BLOCK_FILES:
        target = root / path
        files[path] = merge_block(target.read_text(encoding="utf-8") if target.exists() else None, block())
    return files


def host_of(path: str) -> str:
    if path in BLOCK_FILES:
        return BLOCK_FILES[path]
    if path.startswith((".claude/", ".mcp.json")):
        return "claude"
    if path.startswith((".github/", ".vscode/")):
        return "copilot"
    return "codex"


def write(root: Path, check: bool = False) -> list[str]:
    """Write (or with check=True, only compare) every rendered file. Returns the drifted paths."""
    drifted = []
    for path, content in sorted(expected(root).items()):
        target = root / path
        if target.exists() and target.read_text(encoding="utf-8") == content:
            continue
        drifted.append(path)
        if not check:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
    return drifted
